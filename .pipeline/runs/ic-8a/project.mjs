const doLines = JSON.parse(readFileSync('/Users/m1/kristy/server/lib/doLines.json','utf8'));
const review = readFileSync('/Users/m1/kristy/docs/do-lines-review.md','utf8');
const words = (s) => String(s || '').trim().split(/\s+/).filter(Boolean).length;
const RULE4 = /healthier|healthiest|better for you|chemically ripened|lowers|exposure/i;
const PENDING_OUT = ['olive_oil_grades', 'bottled_water_buying', 'tea'];
const ids = kb.entries.map(e=>e.id); const start = ids.indexOf('sandwich_bread');
const end = ids.findIndex((id,i)=>i>start && /^frozen/.test(id));
const BATCH = kb.entries.slice(start,end).filter(e=>e.kind!=='pick'&&e.kind!=='home');
const notes = kb.entries.map(e=>String(e.tier_note||'').trim()).filter(Boolean);
const rh = (id)=>{const l=review.split('\n').find(l=>l.startsWith(`| \`${id}\` |`));return l?l.split('|')[3].trim():null;};
let fails=0;
for (const e of BATCH){const f=[];const n=String(e.tier_note||'').trim();
 if(words(e.decision)>14)f.push(`front ${words(e.decision)}w`);
 if(headlineHedge(e.decision).length)f.push('hedge '+JSON.stringify(headlineHedge(e.decision)));
 if(words(n)<5)f.push('note short');
 if(/[.!?]\s+\S/.test(n))f.push('note 2 sentences');
 if(/\b(I|me|my|mine|we|us|our)\b/.test(n))f.push('note 1st person');
 if(notes.filter(x=>x===n).length!==1)f.push('note not unique');
 if(TIER_NOTE_ORPHANED_PENDING.has(e.id) && !PENDING_OUT.includes(e.id))f.push('pending');
 const l=lintCard(projectEntry(e,{doLine:doLines[e.id]})); if(l.length)f.push('lint '+JSON.stringify(l));
 const r=readability(e); if(r.length)f.push('read '+JSON.stringify(r));
 if(rh(e.id)!==e.decision)f.push(`review "${rh(e.id)}" vs "${e.decision}"`);
 if(RULE4.test(`${e.decision} ${e.tier_note}`))f.push('rule4 '+`${e.decision} ${e.tier_note}`.match(RULE4)[0]);
 if(f.length){fails++;console.log(e.id+': '+f.join(' | '));}}
